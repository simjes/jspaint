const fs = require("fs");
const path = require("path");

// Anyone can drop a new fun image into images/cursors/multiplayer/ - this
// scans that folder and generates the list src/multiplayer-cursor-images.js
// picks from, so the picker never goes stale waiting for someone to also
// remember to update a hardcoded array. Gitignored, like
// multiplayer-config.js; regenerated at dev/install time.
const imagesDir = path.join(__dirname, "..", "images", "cursors", "multiplayer");
const outPath = path.join(__dirname, "..", "src", "multiplayer-cursor-images.js");

const IMAGE_EXTENSIONS = new Set([".gif", ".png", ".jpg", ".jpeg", ".webp"]);

const filenames = fs.readdirSync(imagesDir)
	.filter((name) => IMAGE_EXTENSIONS.has(path.extname(name).toLowerCase()))
	.sort();

const contents = `// Generated by scripts/generate-cursor-images-manifest.js from the
// contents of images/cursors/multiplayer/ - do not edit directly, and don't
// commit this file (see .gitignore). Re-run \`npm install\` or \`npm run dev\`
// to regenerate it after adding or removing an image there.
export const CURSOR_IMAGES = ${JSON.stringify(filenames, null, "\t")};
`;

fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} with ${filenames.length} cursor image(s)`);
